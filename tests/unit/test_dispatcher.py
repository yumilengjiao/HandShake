def test_bounded_queue_stop_cancels_pending_and_inflight_late_completion_releases():
    clock = Clock()
    c = context(clock)
    block, backend = Event(), None
    backend = MockBackend(block=block)
    d = Dispatcher(c, clock=clock, backend=backend, capacity=1)
    try:
        first = d.submit(command(c, clock))
        assert backend.entered.wait(1)
        pending = d.submit(command(c, clock, command_id="pending", source_event_id="second"))
        full = d.submit(command(c, clock, command_id="overflow", source_event_id="third"))
        assert full.future.result(1).error_code == "queue_full"
        before = time.monotonic()
        d.stop(clock())
        assert time.monotonic() - before < .2
        assert pending.future.result(1).error_code == "stopped_before_commit"
        assert d.wait_released()
        initial_releases = backend.release_calls
        with pytest.raises(RuntimeError, match="quiescence"):
            d.enable(clock())
        block.set()
        first.future.result(1)
        # Wait for the second release request generated by late completion.
        deadline = time.monotonic() + 1
        while backend.release_calls <= initial_releases and time.monotonic() < deadline:
            time.sleep(.001)
        assert backend.release_calls > initial_releases
        assert d.wait_released()
        assert not c.snapshot().enabled
    finally:
        block.set()
        d.close()


