@pytest.mark.parametrize("blocked", [False, True])
def test_external_audit_failure_or_blocking_never_delays_stop_release(blocked):
    clock = Clock()
    c = context(clock)
    entered, unblock = Event(), Event()
    def sink(record):
        entered.set()
        if blocked:
            unblock.wait()
        raise OSError("diagnostic destination unavailable")
    backend = MockBackend()
    d = Dispatcher(c, clock=clock, backend=backend, audit_sink=sink)
    try:
        d.stop()
        assert entered.wait(1)
        assert d.wait_released() and d.safety_status()["safe_quiescent"]
        assert not c.snapshot().enabled
        unblock.set()
        deadline = time.monotonic() + 1
        while d.safety.failures == 0 and time.monotonic() < deadline:
            time.sleep(.001)
        assert d.safety.failures > 0
    finally:
        unblock.set()
        d.close()
