def test_runtime_watchdog_stops_without_any_model_or_ui_callback():
    from backend.interaction.engine import Evidence, InteractionPolicy
    from shared.contracts import ModelPrediction
    controller = ApplicationController("watch", timebase="monotonic")
    policy = InteractionPolicy(health_timeout_ns=30_000_000, score_kind="rule_decision")
    runtime = InteractionRuntime(controller, model_version="rule", policy=policy)
    try:
        runtime.enable()
        controller.bind_owner("t", time.monotonic_ns())
        now = time.monotonic_ns()
        p = ModelPrediction(stream_id="watch", track_id="t", context_epoch=controller.snapshot().context_epoch,
                            source_frame_id=1, source_timestamp_ns=now, inference_timestamp_ns=now,
                            logits=[1., 0., 0., 0., 0.], model_version="rule")
        runtime.update(Evidence(p, True, True, ("t",), static_pose_valid=True, neutral_valid=True, palm_xy=(.5, .5)))
        # No tick/update callback: the independent watchdog must perform this.
        deadline = time.monotonic() + 1
        while not runtime.dispatcher.stopped and time.monotonic() < deadline:
            time.sleep(.005)
        assert runtime.dispatcher.stopped and controller.snapshot().suspended
        assert runtime.dispatcher.wait_released()
    finally:
        runtime.close()


def test_late_absolute_update_is_rejected_and_delta_is_never_silently_dropped():
    from shared.config import ActionsConfig
    clock = Clock()
    c = context(clock)
    cfg = load_config()
    cfg = cfg.model_copy(update={"actions": ActionsConfig(allowlist=["move_pointer", "scroll"], capabilities=["pointer", "scroll"], mappings={"presentation": {
        "no_action": None, "wake_open": None, "swipe_left": "move_pointer", "swipe_right": "scroll", "exit_pose": None}}),
        "platform": cfg.platform.model_copy(update={"capabilities": [Capability.POINTER, Capability.SCROLL]})})
    d = Dispatcher(c, clock=clock, backend=MockBackend(), config=cfg)
    try:
        common = dict(action="move_pointer", required_capabilities=["pointer"], arguments={"x": .5, "y": .5}, control_stream_id="control", update_seq=2)
        assert d.submit(command(c, clock, **common)).future.result(1).accepted
        earlier = command(c, clock, **(common | dict(command_id="earlier", update_seq=1)))
        assert d.submit(earlier).future.result(1).error_code == "stale_continuous_update"
        delta = command(c, clock, command_id="delta", action="scroll", required_capabilities=["scroll"], arguments={"delta": 1.}, control_stream_id="scroll", update_seq=1)
        assert d.submit(delta).future.result(1).accepted
        next_delta = delta.model_copy(update={"command_id": "delta2", "update_seq": 2, "arguments": {"delta": 2.}})
        assert d.submit(next_delta).future.result(1).accepted
        assert sum(c.arguments["delta"] for c in d.backend.commands if c.action.value == "scroll") == 3.
    finally:
        d.close()


