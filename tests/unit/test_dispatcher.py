class Clock:
    def __init__(self):
        self.now = 1_000_000_000

    def __call__(self):
        return self.now


def context(clock):
    controller = ApplicationController("s", timebase="synthetic")
    controller.enable(clock())
    controller.bind_owner("t", clock())
    return controller


def command(controller, clock, **changes):
    c = controller.snapshot()
    return ActionCommand(**(dict(command_id="cmd", source_event_id="event", stream_id="s", context_epoch=c.context_epoch,
                                 action="next_slide", issued_at_ns=clock(), expires_at_ns=clock() + 500_000_000,
                                 required_capabilities=["presentation"], target_context=c.target_context,
                                 timebase="synthetic") | changes))


def test_dry_run_never_claims_injection_and_dedup_covers_new_command_id():
    clock = Clock()
    c = context(clock)
    backend = DryRunBackend()
    d = Dispatcher(c, clock=clock, backend=backend)
    try:
        first = command(c, clock)
        result = d.submit(first).future.result(1)
        assert result.accepted and result.injection_status.value == "not_attempted"
        assert result.acknowledgement_level == "none"
        assert d.submit(first).future.result(1).error_code == "duplicate_command"
        other = first.model_copy(update={"command_id": "new-id"})
        assert d.submit(other).future.result(1).error_code == "duplicate_event"
        assert len(backend.commands) == 1
    finally:
        d.close()


@pytest.mark.parametrize("case,expected", [("expired", "expired"), ("epoch", "stale_context"), ("target", "target_not_allowed"),
                                         ("capability", "BACKEND_UNAVAILABLE"), ("focus", "focus")])
def test_gate_rejects_unavailable_stale_and_expired(case, expected):
    clock = Clock()
